// 获取当前语言
// 优先级：URL 路径 > localStorage > 浏览器语言
window.getCurrentLang = function() {
    var path = window.location.pathname;
    if (path.indexOf('/en/') === 0 || path === '/en') return 'en';
    if (path.indexOf('/zh-cn/') === 0 || path === '/zh-cn') return 'zh-cn';
    var saved = localStorage.getItem('site-lang');
    if (saved) return saved;
    var lang = (navigator.language || navigator.browserLanguage || '').toLowerCase();
    return lang.indexOf('zh') === 0 ? 'zh-cn' : 'en';
};

// 翻译函数
window.t = function(key) {
    var lang = window.getCurrentLang();
    var dict = window.I18N[lang] || window.I18N['zh-cn'];
    return dict[key] || key;
};

// 应用翻译到所有带 data-i18n 属性的元素
window.applyI18n = function() {
    var lang = window.getCurrentLang();
    document.documentElement.lang = lang === 'en' ? 'en' : 'zh-CN';

    // 更新 <title> 和 <meta>
    if (lang === 'en') {
        document.title = 'Lisselde_E - Portfolio';
        document.querySelector('meta[name="description"]').setAttribute('content', 'Lisselde_E\'s personal portfolio featuring LANSyncBox, SyncGUI, DeskHelperGUI and more.');
    } else {
        document.title = 'Lisselde_E - 项目主页';
        document.querySelector('meta[name="description"]').setAttribute('content', 'Lisselde_E 的个人项目主页，包含 LANSyncBox、SyncGUI、DeskHelperGUI 等实用工具。');
    }

    // 遍历所有 data-i18n 元素（替换 textContent）
    document.querySelectorAll('[data-i18n]').forEach(function(el) {
        var key = el.getAttribute('data-i18n');
        var val = window.t(key);
        if (val && val !== key) {
            el.textContent = val;
        }
    });

    // 处理 data-i18n-placeholder 属性（替换 placeholder）
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
        var key = el.getAttribute('data-i18n-placeholder');
        var val = window.t(key);
        if (val && val !== key) {
            el.placeholder = val;
        }
    });

    // 处理 data-i18n-aria-label 属性（替换 aria-label）
    document.querySelectorAll('[data-i18n-aria-label]').forEach(function(el) {
        var key = el.getAttribute('data-i18n-aria-label');
        var val = window.t(key);
        if (val && val !== key) {
            el.setAttribute('aria-label', val);
        }
    });

    // 微软商店徽章图片切换
    var msBadge = lang === 'en' ? 'en-us%20dark.svg' : 'zh-cn%20dark.svg';
    document.querySelectorAll('.ms-store-badge').forEach(function(img) {
        img.src = 'https://get.microsoft.com/images/' + msBadge;
    });

    // Language switch button reference (no longer in sidebar, kept for ?lang= parameter support)
    var switchBtn = document.getElementById('lang-switch');
    if (switchBtn) {
        switchBtn.textContent = window.t('lang.switch');
        switchBtn.title = window.t('lang.switch.title');
    }
};